@pytest.mark.parametrize("rel_path", INPUT_ROOT_ENTRY_POINTS)
def test_input_root_is_required_not_silently_defaulted(rel_path):
    """A missing path must fail loudly, not yield 'Number of human annotations: 0'."""
    src = (ROOT / rel_path).read_text()
    tree = ast.parse(src)
    found = False
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "add_argument"):
            continue
        if not node.args or getattr(node.args[0], "value", None) != "--input_root":
            continue
        found = True
        kw = {k.arg: k.value for k in node.keywords}
        assert "default" not in kw, f"--input_root in {rel_path} must not have a default path"
        assert (
            getattr(kw.get("required"), "value", False) is True
        ), f"--input_root in {rel_path} must be required=True"
    assert found, f"--input_root argument not found in {rel_path}"


@pytest.mark.parametrize("doc", DOC_FILES, ids=lambda p: p.name)
def test_documented_input_root_values_are_parent_directories(doc):
    """--input_root is joined with each scenario folder underneath it, so a
    documented value that is itself a text_dialogue_* path resolves to a
    nonexistent, double-nested directory and silently yields zero annotations.

    Every doc that shows a command counts, not just the README -- this has
    already shipped wrong in docs/ once.
    """
    values = re.findall(r"--input_root\s+(\S+?)\s*\\?\s*$", doc.read_text(), flags=re.MULTILINE)
    bad = [v for v in values if "text_dialogue_" in v]
    assert not bad, f"{doc.name}: --input_root must be the parent of text_dialogue_*, got {bad}"


