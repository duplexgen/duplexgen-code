# Documented commands, and the argparse-owning source file each one runs.
# A package entry point (python -m src.synthesis.run) parses its arguments in
# the module the -m path names, which is not always a module named after the
# package.
DOCUMENTED_ENTRY_POINTS = {
    "src.speechify_run": "src/speechify_run.py",
    "src.train_turntaking_hf": "src/train_turntaking_hf.py",
    "src.inference_turntaking_hf": "src/inference_turntaking_hf.py",
    "src.inference_turntaking_llm": "src/inference_turntaking_llm.py",
    "src.synthesis.run": "src/synthesis/run.py",
    "src.synthesis.run_add_bc": "src/synthesis/run_add_bc.py",
}


def _required_options(rel_path):
    """Every option string argparse marks required=True in a source file.

    Subparser arguments are skipped: they are required only for the subcommand
    that defines them, which this flat scan cannot attribute.
    """
    tree = ast.parse((ROOT / rel_path).read_text())
    subparser_vars = set()
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Assign)
            and isinstance(node.value, ast.Call)
            and getattr(node.value.func, "attr", "") == "add_parser"
        ):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    subparser_vars.add(target.id)

    required = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "add_argument"):
            continue
        if getattr(node.func.value, "id", None) in subparser_vars:
            continue
        kw = {k.arg: k.value for k in node.keywords}
        if getattr(kw.get("required"), "value", False) is not True:
            continue
        flags = [a.value for a in node.args if isinstance(getattr(a, "value", None), str)]
        opts = [f for f in flags if f.startswith("-")]
        if opts:
            required.append(opts)
    return required


def _documented_commands():
    """(doc name, module, full command text) for every `-m src.<module>` in a code block."""
    found = []
    for doc in DOC_FILES:
        for block in re.findall(r"```bash\n(.*?)```", doc.read_text(), flags=re.DOTALL):
            # Join backslash continuations so a multi-line command is one string.
            for command in re.sub(r"\\\n\s*", " ", block).splitlines():
                match = re.search(r"-m\s+(src\.[\w.]+)", command)
                if match:
                    found.append((doc.name, match.group(1), command))
    return found


def test_every_documented_module_is_a_known_entry_point():
    unknown = {m for _, m, _ in _documented_commands() if m not in DOCUMENTED_ENTRY_POINTS}
    assert (
        not unknown
    ), f"documented modules missing from DOCUMENTED_ENTRY_POINTS: {sorted(unknown)}"


def test_documented_commands_pass_every_required_argument():
    """A documented command that omits a required= argument dies on argparse.

    README's Stage 3 example ran `-m src.inference_turntaking_llm --split test
    --scenarios all` and exited 2 with "the following arguments are required:
    --input_root" before doing any work.
    """
    broken = []
    for doc_name, module, command in _documented_commands():
        for aliases in _required_options(DOCUMENTED_ENTRY_POINTS[module]):
            if not any(
                re.search(rf"(?<![\w-]){re.escape(a)}(?=[\s=]|$)", command) for a in aliases
            ):
                broken.append(f"{doc_name}: `{module}` omits required {'/'.join(aliases)}")
    assert not broken, "documented commands fail argparse:\n  " + "\n  ".join(broken)


